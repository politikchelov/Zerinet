-- ZERINET social backend schema. Apply in Supabase SQL Editor if migrations are not deployed automatically.
create extension if not exists pgcrypto;

create table if not exists public.zerinet_users (
  id bigint generated by default as identity primary key,
  name text not null unique,
  name_key text not null unique,
  password_salt text not null,
  password_hash text not null,
  role text not null default 'user' check (role in ('user','admin')),
  rank text not null default 'novice',
  points integer not null default 0,
  bio text not null default '',
  avatar text,
  created bigint not null default extract(epoch from now())::bigint,
  last_seen bigint not null default extract(epoch from now())::bigint,
  banned boolean not null default false,
  ban_reason text not null default '',
  muted_until bigint not null default 0
);
create table if not exists public.zerinet_sessions (
  token_hash text primary key,
  user_id bigint not null references public.zerinet_users(id) on delete cascade,
  expires bigint not null
);
create index if not exists zerinet_sessions_expiry_idx on public.zerinet_sessions(expires);
create table if not exists public.zerinet_friends (
  user_id bigint not null references public.zerinet_users(id) on delete cascade,
  other_id bigint not null references public.zerinet_users(id) on delete cascade,
  status text not null check (status in ('pending','accepted')),
  created bigint not null default extract(epoch from now())::bigint,
  primary key(user_id, other_id)
);
create table if not exists public.zerinet_chat (
  id bigint generated by default as identity primary key,
  user_id bigint references public.zerinet_users(id) on delete set null,
  kind text not null default 'msg',
  text text not null,
  created bigint not null default extract(epoch from now())::bigint,
  deleted boolean not null default false
);
create index if not exists zerinet_chat_visible_idx on public.zerinet_chat(id desc) where deleted = false;
create table if not exists public.zerinet_comments (
  id bigint generated by default as identity primary key,
  alias text not null,
  user_id bigint not null references public.zerinet_users(id) on delete cascade,
  text text not null,
  created bigint not null default extract(epoch from now())::bigint,
  deleted boolean not null default false
);
create index if not exists zerinet_comments_alias_idx on public.zerinet_comments(alias, id desc) where deleted = false;
alter table public.zerinet_users enable row level security;
alter table public.zerinet_sessions enable row level security;
alter table public.zerinet_friends enable row level security;
alter table public.zerinet_chat enable row level security;
alter table public.zerinet_comments enable row level security;
